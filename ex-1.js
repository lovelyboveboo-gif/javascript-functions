// Start coding here "Declaring the Functions"
function add(a,b) {
    return a + b;    
}

function subtract(a,b) {
    return a - b;
}

function multiply(a,b) {
    return a * b;    
}

function divide(a,b) {
    return a / b;
}

console.log(add(25,49));
console.log(subtract(82,41));
console.log(multiply(79,15));
console.log(divide(144,12));