// Start coding here "Declaring Arrow Function"
const add = (a,b) => {
    return a + b;    
};

const subtract = (a,b) => {
    return a - b;
};

const multiply = (a,b) => {
    return a * b;    
};

const divide = (a,b) => {
    return a / b;
};

console.log(add(25,49));
console.log(subtract(82,41));
console.log(multiply(79,15));
console.log(divide(144,12));



